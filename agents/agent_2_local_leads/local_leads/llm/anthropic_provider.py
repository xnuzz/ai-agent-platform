"""Anthropic (Claude) provider - default LLM for brief and outreach writing.

Messages API with structured outputs (`output_config.format` = JSON schema), so the first text block is
valid JSON for the schema. Server-side refusal fallback is opted in by default (`fallbacks: "default"`,
beta `server-side-fallback-2026-07-01`; Claude API only - set LLM_SERVER_FALLBACK=false for other
platforms/models). The SDK retries 408/409/429/5xx and connection errors (`max_retries`); what is still
failing afterwards is raised as LLMUnavailable and the caller falls back to templates.
"""
from __future__ import annotations

import json
import logging

from ..config import DEFAULT_LLM_MODEL
from .base import LLMError, LLMProvider, LLMRefusal, LLMUnavailable, wire_schema

logger = logging.getLogger("local_leads.llm.anthropic")
FALLBACK_BETA = "server-side-fallback-2026-07-01"
EFFORTS = {"low", "medium", "high", "xhigh", "max"}


class AnthropicProvider(LLMProvider):
    name = "anthropic"

    def __init__(self, *, model: str = DEFAULT_LLM_MODEL, api_key: str = "", effort: str = "medium",
                 timeout: float = 120.0, max_retries: int = 2, server_fallback: bool = True, client=None):
        import anthropic  # imported lazily: the package works without the SDK when another provider is used

        self._sdk = anthropic
        self.model = model or DEFAULT_LLM_MODEL
        self.effort = effort if effort in EFFORTS else None   # "none"/"" -> omit (older models without effort)
        self.server_fallback = server_fallback
        # api_key=None lets the SDK resolve ANTHROPIC_API_KEY / profiles; LLM_API_KEY takes precedence.
        self.client = client or anthropic.Anthropic(api_key=api_key or None, timeout=timeout,
                                                    max_retries=max_retries)

    def generate_json(self, *, task: str, system: str, prompt: str, schema: dict, max_tokens: int = 8000) -> dict:
        sdk = self._sdk
        output_config: dict = {"format": {"type": "json_schema", "schema": wire_schema(schema)}}
        if self.effort:
            output_config["effort"] = self.effort
        kwargs = dict(model=self.model, max_tokens=max_tokens, system=system,
                      messages=[{"role": "user", "content": prompt}], output_config=output_config)
        try:
            if self.server_fallback:
                resp = self.client.beta.messages.create(**kwargs, betas=[FALLBACK_BETA], fallbacks="default")
            else:
                resp = self.client.messages.create(**kwargs)
        except (sdk.AuthenticationError, sdk.PermissionDeniedError, sdk.NotFoundError) as exc:
            raise LLMError(f"{task}: provider configuration error ({type(exc).__name__}): {exc}") from exc
        except sdk.BadRequestError as exc:
            raise LLMError(f"{task}: request rejected: {exc}") from exc
        except sdk.RateLimitError as exc:
            raise LLMUnavailable(f"{task}: rate limited") from exc
        except sdk.APIStatusError as exc:
            if exc.status_code >= 500:
                raise LLMUnavailable(f"{task}: provider error HTTP {exc.status_code}") from exc
            raise LLMError(f"{task}: HTTP {exc.status_code}: {exc}") from exc
        except sdk.APIConnectionError as exc:  # includes APITimeoutError
            raise LLMUnavailable(f"{task}: connection error: {exc}") from exc

        request_id = getattr(resp, "_request_id", None)
        if resp.stop_reason == "refusal":
            details = getattr(resp, "stop_details", None)
            raise LLMRefusal(f"{task}: model declined (category={getattr(details, 'category', None)}, "
                             f"request_id={request_id})")
        if resp.stop_reason == "max_tokens":
            raise LLMError(f"{task}: output truncated at max_tokens (request_id={request_id})")
        text = next((b.text for b in resp.content if getattr(b, "type", "") == "text"), None)
        if not text:
            raise LLMError(f"{task}: no text block in response (request_id={request_id})")
        try:
            data = json.loads(text)
        except ValueError as exc:
            raise LLMError(f"{task}: response is not valid JSON (request_id={request_id})") from exc
        if not isinstance(data, dict):
            raise LLMError(f"{task}: expected a JSON object")
        logger.debug("%s generated by %s (request_id=%s)", task, getattr(resp, "model", self.model), request_id)
        return data
