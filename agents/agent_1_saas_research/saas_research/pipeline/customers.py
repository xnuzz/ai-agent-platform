"""Step 4 (SAAS_CUSTOMER_RESEARCH): find potential customer businesses and their *published* contact addresses.

Pipeline: plan queries (LLM, sanitised; deterministic fallback) -> search -> LLM assesses which results are single
businesses that fit the approved idea -> fetch each business website (+ common contact pages) -> keep only email
addresses literally present on the business's own domain -> classify address type + legal basis.

Emails are never generated by the model; they come from fetched pages only.
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field

from ..errors import InvalidTaskInput
from ..evidence import EvidenceRecord, EvidenceRegistry
from ..llm.base import LLMProvider, render_input
from ..schemas import BusinessAssessments, CustomerSearchPlan
from ..sources.base import PageFetcher, SearchProvider, domain_of, origin_of
from .common import GROUNDING_RULES, squash, stable_ref, truncate
from .research import PlannedQuery

logger = logging.getLogger("saas_research.pipeline.customers")

CONTACT_PATHS = ("/contact", "/contact-us", "/kontakt", "/impressum", "/about")
GENERIC_LOCAL_PARTS = {
    "info", "contact", "hello", "hi", "office", "mail", "sales", "team", "enquiries", "inquiries", "enquiry",
    "kontakt", "admin", "booking", "bookings", "reception", "support", "service", "studio", "praxis", "shop",
    "orders", "welcome", "general", "post", "office.manager", "frontdesk", "appointments", "help", "billing",
}
PERSONAL_RE = re.compile(r"^[a-z]{2,}[._-][a-z]{2,}$")
_ROLE_PREFIXES = ("no-reply", "noreply", "donotreply", "postmaster", "abuse", "webmaster", "privacy", "dpo", "gdpr",
                  "jobs", "careers", "press", "legal")


@dataclass(frozen=True)
class CustomerRequest:
    """SAAS_CUSTOMER_RESEARCH input + approved idea from task.context (docs/AGENT_1_CONTRACT.md)."""
    software_idea: dict
    opportunity: dict | None
    regions: tuple[str, ...] = ()
    max_leads: int = 25
    channels: tuple[str, ...] = ("EMAIL",)
    language: str = "en"
    notes: str = ""

    @classmethod
    def from_task(cls, data: dict, context: dict) -> "CustomerRequest":
        idea = (context or {}).get("software_idea")
        if not isinstance(idea, dict) or not idea.get("name"):
            raise InvalidTaskInput("task.context.software_idea is missing; customer research needs an approved idea")
        if idea.get("status") and idea["status"] != "APPROVED":
            raise InvalidTaskInput(f"software idea is {idea['status']}, expected APPROVED")
        if data.get("software_idea_id") and idea.get("id") and str(data["software_idea_id"]) != str(idea["id"]):
            raise InvalidTaskInput("task.context.software_idea does not match input.software_idea_id")
        return cls(
            software_idea=idea, opportunity=(context or {}).get("opportunity") or None,
            regions=tuple(str(r).upper()[:2] for r in (data.get("regions") or []) if r),
            max_leads=max(1, min(int(data.get("max_leads") or 25), 200)),
            channels=tuple(str(c).upper() for c in (data.get("channels") or ["EMAIL"])),
            language=str(data.get("language") or "en")[:10],
            notes=str(data.get("notes") or "")[:2000],
        )

    def idea_view(self) -> dict:
        i = self.software_idea
        view = {k: i.get(k) for k in ("name", "summary", "problem", "solution", "target_customers", "key_features",
                                       "pricing_model", "differentiation", "mvp_scope") if i.get(k)}
        if self.opportunity:
            view["opportunity"] = {k: self.opportunity.get(k) for k in ("title", "problem_statement", "industry",
                                                                         "target_segment") if self.opportunity.get(k)}
        return view


@dataclass
class Candidate:
    """A potential customer business (and, after contact discovery, its lead)."""
    ref: str
    name: str
    website: str
    category: str
    city: str
    country_code: str
    fit_score: int
    fit_rationale: str
    source: EvidenceRecord
    email: str = ""
    email_type: str = "UNKNOWN"
    contact_evidence: EvidenceRecord | None = None
    extra: dict = field(default_factory=dict)

    @property
    def domain(self) -> str:
        return domain_of(self.website)

    @property
    def lead_ref(self) -> str:
        return "lead-" + self.ref.split("-", 1)[1]


# ---------------------------------------------------------------- query planning
PLAN_SYSTEM = f"""You plan web searches that find the websites of individual businesses that are likely buyers of \
the given software product.
{GROUNDING_RULES}
- Queries should find specific businesses (e.g. "dental clinic Sofia"), not articles or software vendors.
- Use the local language of the target country when it helps. country_code must be one of the requested regions \
(or empty when no regions are given)."""


def fallback_queries(req: CustomerRequest, limit: int) -> list[PlannedQuery]:
    target = squash(req.software_idea.get("target_customers") or "") or squash(
        (req.opportunity or {}).get("target_segment") or "") or squash((req.opportunity or {}).get("industry") or "")
    target = truncate(target or req.software_idea["name"], 120)
    countries = list(req.regions) or [None]
    qs = [PlannedQuery(f"{target} contact", c) for c in countries]
    qs += [PlannedQuery(f"{target} official website", c) for c in countries]
    return qs[:limit]


def plan_customer_queries(llm: LLMProvider, req: CustomerRequest, *, max_queries: int) -> list[PlannedQuery]:
    payload = {"task": "plan_customer_search", "idea": req.idea_view(), "regions": list(req.regions),
               "language": req.language, "user_notes": req.notes, "max_queries": max_queries}
    out = llm.generate(system=PLAN_SYSTEM, prompt=f"Plan up to {max_queries} searches.\n{render_input(payload)}",
                       output_model=CustomerSearchPlan)
    allowed = set(req.regions)
    seen: dict[tuple[str, str | None], None] = {}
    for q in out.queries:
        text = truncate(squash(q.query), 200)
        cc = (q.country_code or "").upper() or None
        if not text:
            continue
        if allowed and cc not in allowed:
            cc = sorted(allowed)[len(seen) % len(allowed)]
        if not allowed:
            cc = None
        seen.setdefault((text, cc), None)
    planned = [PlannedQuery(t, c) for t, c in seen][:max_queries]
    covered = {p.country for p in planned}
    for p in fallback_queries(req, max_queries):  # make sure every requested region is searched
        if p.country not in covered:
            planned.append(p)
            covered.add(p.country)
    return planned or fallback_queries(req, max_queries)


def search_candidates(search: SearchProvider, queries: list[PlannedQuery], registry: EvidenceRegistry, *,
                      results_per_query: int, language: str | None, on_query=None) -> list[EvidenceRecord]:
    """Run searches; return one evidence record per distinct domain (first hit wins)."""
    by_domain: dict[str, EvidenceRecord] = {}
    for i, q in enumerate(queries):
        for r in search.search(q.query, max_results=results_per_query, country=q.country, language=language):
            rec = registry.add_search_result(r)
            if rec is not None:
                by_domain.setdefault(domain_of(rec.url), rec)
        if on_query:
            on_query(i + 1, len(queries))
    return list(by_domain.values())


# ---------------------------------------------------------------- assessment
ASSESS_SYSTEM = f"""You qualify search results as potential customers for a B2B software product.
{GROUNDING_RULES}
- is_individual_business is true only for the own website or profile of ONE business that could buy the product. \
Lists, rankings, news, marketplaces, directories' overview pages, software vendors and competitors are false.
- business_name and city must appear in the source title/excerpt; otherwise leave them empty.
- fit_score 0-100: how well the business matches the product's target customers."""


def assess_candidates(llm: LLMProvider, req: CustomerRequest, records: list[EvidenceRecord], *,
                      min_fit: int, batch_size: int = 40) -> list[Candidate]:
    candidates: list[Candidate] = []
    by_sid = {r.sid: r for r in records}
    for start in range(0, len(records), batch_size):
        chunk = records[start:start + batch_size]
        payload = {"task": "assess_businesses", "idea": req.idea_view(), "language": req.language,
                   "user_notes": req.notes, "sources": [r.prompt_view(500) for r in chunk]}
        out = llm.generate(system=ASSESS_SYSTEM, prompt=f"Assess every source.\n{render_input(payload)}",
                           output_model=BusinessAssessments)
        for a in out.assessments:
            rec = by_sid.get(a.source_id.strip())
            if rec is None or not a.is_individual_business or a.fit_score < min_fit:
                continue
            haystack = f"{rec.title} {rec.excerpt}".lower()
            name = truncate(squash(a.business_name), 300)
            if not name or name.lower() not in haystack:
                name = truncate(rec.title.split(" | ")[0].split(" - ")[0], 300) or rec.url
            city = truncate(squash(a.city), 120)
            if city and city.lower() not in haystack:
                city = ""  # not grounded in the source -> do not assert it
            candidates.append(Candidate(
                ref=stable_ref("biz", domain_of(rec.url)), name=name, website=origin_of(rec.url) + "/",
                category=truncate(squash(a.category), 200), city=city,
                country_code=str(rec.metadata.get("country_code") or "")[:2], fit_score=a.fit_score,
                fit_rationale=truncate(squash(a.fit_rationale), 1000), source=rec))
    unique: dict[str, Candidate] = {}
    for c in sorted(candidates, key=lambda c: -c.fit_score):
        unique.setdefault(c.domain, c)
    return list(unique.values())


# ---------------------------------------------------------------- contacts
def domains_match(email_domain: str, site_domain: str) -> bool:
    e, s = email_domain.lower().removeprefix("www."), site_domain.lower().removeprefix("www.")
    return e == s or e.endswith("." + s) or s.endswith("." + e)


def classify_email(email: str) -> str:
    """-> ContactEmailType: GENERIC_BUSINESS | PERSONAL_WORK | UNKNOWN."""
    local = email.split("@", 1)[0].lower()
    if local in GENERIC_LOCAL_PARTS or local.split("+")[0] in GENERIC_LOCAL_PARTS:
        return "GENERIC_BUSINESS"
    if PERSONAL_RE.match(local):
        return "PERSONAL_WORK"
    return "UNKNOWN"


_TYPE_RANK = {"GENERIC_BUSINESS": 0, "UNKNOWN": 1, "PERSONAL_WORK": 2}


def pick_email(emails: tuple[str, ...], site_domain: str) -> tuple[str, str] | None:
    """Best published address on the business's own domain: generic > unknown > personal. None if none."""
    options = []
    for e in emails:
        if "@" not in e or e.split("@", 1)[0].startswith(_ROLE_PREFIXES):
            continue
        if not domains_match(e.split("@", 1)[1], site_domain):
            continue
        options.append((_TYPE_RANK[classify_email(e)], e))
    if not options:
        return None
    _, email = min(options)
    return email, classify_email(email)


def legal_basis_for(c: Candidate) -> tuple[str, str]:
    """Honest legal-basis assessment. Only generic business addresses get LEGITIMATE_INTEREST; anything that may
    identify a person is UNKNOWN (the backend then refuses to send until a human sets a basis)."""
    if c.email_type == "GENERIC_BUSINESS":
        src = c.contact_evidence.url if c.contact_evidence else c.website
        return ("LEGITIMATE_INTEREST",
                f"Generic business address published on the company's own website ({src}); B2B offer relevant to "
                f"its business. Agent assessment only — confirm for your jurisdiction (platform consent rules "
                f"still apply).")
    return ("UNKNOWN",
            "Address may identify an individual or its type is unclear; legal basis not assessed. A human must "
            "review and set a legal basis before this lead can be contacted.")


def find_contacts(fetcher: PageFetcher, candidates: list[Candidate], registry: EvidenceRegistry, *,
                  max_leads: int, contact_paths: tuple[str, ...] = CONTACT_PATHS, on_candidate=None
                  ) -> list[Candidate]:
    """Fetch websites until `max_leads` contactable candidates are found (in fit order)."""
    found: list[Candidate] = []
    for i, c in enumerate(candidates):
        if len(found) >= max_leads:
            break
        urls = [c.website] + [c.website.rstrip("/") + p for p in contact_paths]
        best: tuple[str, str] | None = None
        best_page = None
        for url in urls:
            page = fetcher.fetch(url)
            if page is None or not domains_match(domain_of(page.url), c.domain):
                continue
            pick = pick_email(page.emails, c.domain)
            if pick and (best is None or _TYPE_RANK[pick[1]] < _TYPE_RANK[best[1]]):
                best, best_page = pick, page
            if best and best[1] == "GENERIC_BUSINESS":
                break
        if on_candidate:
            on_candidate(i + 1, len(candidates))
        if best is None or best_page is None:
            continue
        email, etype = best
        pos = best_page.text.lower().find(email)
        excerpt = best_page.text[max(0, pos - 200): pos + len(email) + 100] if pos >= 0 else f"mailto:{email}"
        c.email, c.email_type = email, etype
        c.contact_evidence = registry.add_page(best_page, excerpt=excerpt, source_type="WEB_PAGE",
                                               metadata={"purpose": "contact_details"})
        found.append(c)
    return found
